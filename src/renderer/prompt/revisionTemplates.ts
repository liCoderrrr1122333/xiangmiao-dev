export function buildRevisionPrompt(issues: string[], wardrobeEnabled = false) {
  const details = issues.map((issue) => issueMap[issue]).filter(Boolean).join('\n');
  const scope = wardrobeEnabled
    ? `只允许重新处理人脸、为匹配主参考图所必需的目标人物头发区域和已经指定的服饰配饰目标区域。${faceReferenceResponsibility} 穿搭继续分别参考衣物与配饰参考图。除这些授权区域外，背景、身体比例、姿态、手部、未指定服饰道具、构图、光影、画质和噪点都必须恢复或保持原图不变。`
    : `只允许重新处理人脸和为匹配主参考图所必需的目标人物头发区域。${faceReferenceResponsibility} 请恢复或保持其他内容，包括背景、身体、衣服、手部、道具、构图、光影、画质和噪点；人脸继续匹配原图的光影、面部朝向、皮肤纹理和真实拍摄质感。`;
  const coreRule = wardrobeEnabled
    ? '人脸与目标人物头发按主参考图修改，穿搭只在指定服饰配饰目标区域修改，其余内容完全不变。'
    : '人脸与目标人物头发按主参考图修改，其余内容完全不变。';
  return `请基于上一张生成结果进行修正。

当前主要问题：${issues.length ? issues.join('、') : '需要进一步提升红圈内人脸融合质量'}。

${details}

请不要重新生成整张图。${scope}

核心规则：${coreRule}`;
}
